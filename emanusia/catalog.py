# opções que valem para qualquer passo de ferramenta
STEP_OPTIONS = [
    F("if", "Só fazer se", "condition", key="if"),
    F("on_error", "Se der erro", "select", key="on_error", options=[["stop", "Parar o robô"], ["continue", "Seguir em frente"]],
      default="stop"),
    F("retry", "Tentar de novo (vezes)", "number", key="retry"),
    F("comment", "Anotação", key="comment"),
]

KIND = {"string": "text", "integer": "number", "number": "number", "boolean": "bool", "array": "json", "object": "json"}


def catalog(user=None) -> dict:
    """Catálogo pronto para a tela: ações curadas + uma peça genérica para cada ferramenta restante."""
    covered = {a["tool"] for a in ACTIONS if a.get("tool")}
    actions = []
    for a in ACTIONS:
        d = dict(a)
        if d.get("tool"):
            try:
                t = registry.get(d["tool"])
            except KeyError:
                continue  # módulo opcional ausente
            d["risky"] = bool(t.risky)
            d["allowed"] = user is None or user.may_use_tool(t.name)
            names = {f["name"] for f in d["fields"]}
            # o resto dos argumentos da ferramenta fica em "Avançado", com o tipo do esquema
            d["fields"] = d["fields"] + [F(k, k.replace("_", " ").capitalize(), KIND.get(v.get("type"), "json"),
                                           adv=True, options=[[o, o] for o in v["enum"]] if v.get("enum") else None)
                                         for k, v in t.parameters.items() if k not in names]
        actions.append(d)
    for t in sorted(registry.all_tools(), key=lambda t: t.name):
        if t.name in covered or t.group in ("workflow", "botops") or t.name.startswith("t_"):
            continue
        actions.append(dict(id=t.name, cat="other", tool=t.name, title=t.name, desc=t.description,
                            risky=bool(t.risky), allowed=user is None or user.may_use_tool(t.name),
                            fields=[F(k, k.replace("_", " ").capitalize(), KIND.get(v.get("type"), "json"),
                                      required=k in t.required,
                                      options=[[o, o] for o in v["enum"]] if v.get("enum") else None)
                                    for k, v in t.parameters.items()] + [SAVE("resultado")]))
    cats = [{"id": c, "icon": i, "name": n, "desc": d} for c, i, n, d in CATEGORIES]
    if any(a["cat"] == "other" for a in actions):
        cats.append({"id": "other", "icon": "🧰", "name": "Outras ações", "desc": "Todas as demais ferramentas"})
    for a in actions:  # limpa opções vazias
        for f in a.get("fields", []):
            if f.get("options") is None:
                f.pop("options", None)
    return {"categories": cats, "actions": actions, "step_options": STEP_OPTIONS, "templates": TEMPLATES}
